import json


class Book:
    def __init__(self, title, author, available=True):
        self.title = title
        self.author = author
        self.available = available

    def borrow(self):
        if self.available == False:
            return False
        self.available = False
        return True

    def give_back(self):
        if self.available == True:
            return False
        self.available = True
        return True

    def __str__(self):
        if self.available:
            status = "Available"
        else:
            status = "Borrowed"
        return f"{self.title} by {self.author} [{status}]"


class Library:
    def __init__(self, filename="library.json"):
        self.filename = filename
        self.books = []
        self.load()

    def save(self):
        data = []
        for b in self.books:
            data.append({"title": b.title, "author": b.author, "available": b.available})
        with open(self.filename, "w") as f:
            json.dump(data, f)

    def load(self):
        try:
            with open(self.filename) as f:
                data = json.load(f)
        except (FileNotFoundError, json.JSONDecodeError):
            return
        for d in data:
            self.books.append(Book(d["title"], d["author"], d["available"]))

    def add_book(self, title, author):
        title = title.strip().title()
        author = author.strip().title()
        if title == "" or author == "":
            print("Title and author are required")
            return
        if self.find(title) is not None:
            print("This book already exists")
            return
        self.books.append(Book(title, author))
        self.save()
        print("Book added")

    def find(self, title):
        title = title.strip().title()
        for b in self.books:
            if b.title == title:
                return b
        return None

    def show_all(self):
        if len(self.books) == 0:
            print("No books yet")
            return
        for i, b in enumerate(self.books, 1):
            print(f"{i}. {b}")

    def show_available(self):
        found = False
        for b in self.books:
            if b.available:
                print(b)
                found = True
        if not found:
            print("No available books")

    def borrow_book(self, title):
        book = self.find(title)
        if book is None:
            print("Book not found")
            return
        if book.borrow():
            self.save()
            print(f"You borrowed: {book.title}")
        else:
            print("Sorry, this book is already borrowed")

    def return_book(self, title):
        book = self.find(title)
        if book is None:
            print("Book not found")
            return
        if book.give_back():
            self.save()
            print(f"Thank you for returning: {book.title}")
        else:
            print("This book was not borrowed")


def main():
    lib = Library()
    while True:
        print()
        print("1. Add book")
        print("2. View all books")
        print("3. View available books")
        print("4. Borrow a book")
        print("5. Return a book")
        print("6. Quit")
        choice = input("Choose: ").strip()

        if choice == "1":
            title = input("Title: ")
            author = input("Author: ")
            lib.add_book(title, author)
        elif choice == "2":
            lib.show_all()
        elif choice == "3":
            lib.show_available()
        elif choice == "4":
            lib.borrow_book(input("Title to borrow: "))
        elif choice == "5":
            lib.return_book(input("Title to return: "))
        elif choice == "6":
            break
        else:
            print("Invalid choice")

    print("Goodbye")


main()

